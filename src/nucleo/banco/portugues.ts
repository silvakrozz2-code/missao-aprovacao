export interface Obra { autor: string; obra: string; escola: string }
/** Literatura brasileira: obra → autor e autor → escola. */
export function literatura(pref: string, materia: string, tema: string, obras: Obra[], nivel: "basico" | "intermediario" = "intermediario"): Gerador[] {
  const autores = [...new Map(obras.map((o) => [o.autor, o])).values()];
  return [
    ...deFatos({
      id: `${pref}-obra`, materia, tema, nivel,
      itens: obras.map((o) => [o.obra, o.autor, `Escola: ${o.escola}.`]),
      perg: (k) => `A obra "${k}" foi escrita por:`,
      inv: (v) => `Assinale a obra escrita por ${v}.`,
    }),
    ...deFatos({
      id: `${pref}-esc`, materia, tema, nivel: "intermediario",
      itens: autores.map((o) => [o.autor, o.escola]),
      perg: (k) => `${k} é um autor associado a qual escola ou período literário?`,
      inv: (v) => `Assinale o autor associado à escola ou período literário "${v}".`,
    }),
  ];
}

